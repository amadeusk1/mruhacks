"""Regenerate the vault's Renders.md gallery from Renders/Kits and Renders/Details.
Runs at the end of build.py; also runnable with plain python3."""
import os, json, glob, datetime

VAULT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
R = os.path.join(VAULT, "Renders")
MODELS = os.path.join(VAULT, "Models")

GROUPS = [  # (heading, kits) in the order a reader cares about
    ("Characters", ["avatar", "pets"]),
    ("Town", ["plaza", "nature_dock", "town_connections", "buildings", "cafe", "cottage", "building_finishing", "world_misc"]),
    ("Cinema", ["cinema", "cinema_lobby", "cinema_auditorium"]),
    ("Arcade", ["arcade"]),
    ("Activities", ["fishing", "winter", "activities", "interaction_props"]),
    ("Housing", ["homes", "room_kit", "home_themes", "interior_finishing"]),
    ("Effects", ["fx"]),
]


def count(kit):
    p = os.path.join(MODELS, kit, "manifest.json")
    return len(json.load(open(p))) if os.path.exists(p) else 0


def main():
    kits = {os.path.splitext(f)[0] for f in os.listdir(os.path.join(R, "Kits"))} if os.path.isdir(os.path.join(R, "Kits")) else set()
    details = sorted(os.listdir(os.path.join(R, "Details"))) if os.path.isdir(os.path.join(R, "Details")) else []
    known = {k for _, ks in GROUPS for k in ks}
    lines = ["# Renders", "",
             "Generated by `art/blender/render_index.py` after each build. Do not edit by hand.",
             f"Last build: {datetime.datetime.now():%Y-%m-%d %H:%M}. See [[Art Pipeline]] for how assets are made.", ""]
    for head, ks in GROUPS + [("Other", sorted(kits - known))]:
        present = [k for k in ks if k in kits]
        if not present:
            continue
        lines += [f"## {head}", ""]
        for k in present:
            lines += [f"### {k.replace('_', ' ').title()} ({count(k)} assets)", "", f"![[Renders/Kits/{k}.png]]", ""]
            for d in [d for d in details if d.startswith(k + "_")]:
                lines += [f"![[Renders/Details/{d}]]", ""]
    open(os.path.join(VAULT, "Renders.md"), "w").write("\n".join(lines))
    models_index()


def models_index():
    """Models.md: every GLB with its size and sockets, grouped like Renders.md."""
    have = {d for d in os.listdir(MODELS) if os.path.exists(os.path.join(MODELS, d, "manifest.json"))} if os.path.isdir(MODELS) else set()
    known = {k for _, ks in GROUPS for k in ks}
    total = sum(count(k) for k in have)
    out = ["# Models", "",
           "Generated by `art/blender/render_index.py` after each build. Do not edit by hand.",
           f"{total} GLB assets in `Models/<kit>/`, one file per asset, plus `manifest.json` per kit. "
           "`Models/all_assets.blend` holds every kit in one Blender file. See [[Art Pipeline]] for conventions and [[Renders]] for pictures.", ""]
    for head, ks in GROUPS + [("Other", sorted(have - known))]:
        present = [k for k in ks if k in have]
        if not present:
            continue
        out += [f"## {head}", ""]
        for k in present:
            man = json.load(open(os.path.join(MODELS, k, "manifest.json")))
            out += [f"### {k.replace('_', ' ').title()}", "", "| Model | Size (m) | Tints | Sockets |", "| --- | --- | --- | --- |"]
            for a in man:
                size = " × ".join(f"{v:g}" for v in a.get("size_m", []))
                tints = ", ".join(a.get("tints", {}) or [])
                socks = len(a.get("sockets", {}) or {})
                out.append(f"| [[Models/{a['file']}\\|{os.path.basename(a['file'])[:-4]}]] | {size} | {tints} | {socks} |")
            out.append("")
    open(os.path.join(VAULT, "Models.md"), "w").write("\n".join(out))


if __name__ == "__main__":
    main()
